using System.Text.Json;

namespace AgentHub.Agents.Pipeline.Ta;

/// <summary>Writes HTTP smoke automation under tests/e2e for the live deployed URL.</summary>
public static class DeployedSmokeGenerator
{
    private static readonly JsonSerializerOptions JsonOptions = new(JsonSerializerDefaults.Web)
    {
        WriteIndented = true
    };

    public static IReadOnlyList<SmokeCase> DefaultCases(string? stackProfile)
    {
        var cases = new List<SmokeCase>
        {
            new("HealthOk", "GET", "/health", 200, "ok")
        };

        if (string.Equals(stackProfile, "fe-be-llm", StringComparison.OrdinalIgnoreCase))
        {
            cases.Add(new("Thought", "GET", "/api/thought", 200, "thought"));
        }
        else
        {
            cases.Add(new("Add", "GET", "/api/add?a=2&b=3", 200, "\"result\":5"));
        }

        return cases;
    }

    public static IReadOnlyList<SmokeCase> ParseCasesOrDefault(string? llmText, string? stackProfile)
    {
        var json = ExtractJson(llmText);
        if (json is null)
        {
            return DefaultCases(stackProfile);
        }

        try
        {
            using var doc = JsonDocument.Parse(json);
            if (!doc.RootElement.TryGetProperty("cases", out var arr) || arr.ValueKind != JsonValueKind.Array)
            {
                return DefaultCases(stackProfile);
            }

            var list = new List<SmokeCase>();
            foreach (var el in arr.EnumerateArray())
            {
                var name = el.TryGetProperty("name", out var n) ? n.GetString() ?? "case" : "case";
                var method = el.TryGetProperty("method", out var m) ? m.GetString() ?? "GET" : "GET";
                var path = el.TryGetProperty("path", out var p) ? p.GetString() ?? "/health" : "/health";
                var status = el.TryGetProperty("expectStatus", out var s) && s.TryGetInt32(out var code) ? code : 200;
                var contains = el.TryGetProperty("expectBodyContains", out var c) ? c.GetString() : null;
                list.Add(new SmokeCase(name, method, path, status, contains));
            }

            return list.Count > 0 ? list : DefaultCases(stackProfile);
        }
        catch (JsonException)
        {
            return DefaultCases(stackProfile);
        }
    }

    public static void WriteSuite(string monoRoot, IReadOnlyList<SmokeCase> cases)
    {
        var dir = Path.Combine(monoRoot, "tests", "e2e");
        Directory.CreateDirectory(dir);
        File.WriteAllText(
            Path.Combine(dir, "cases.json"),
            JsonSerializer.Serialize(new { cases }, JsonOptions));
        var scriptPath = Path.Combine(dir, "deployed-smoke.sh");
        File.WriteAllText(scriptPath, RunnerScript);
        // Executable bit is nice-to-have; TA always invokes via `bash <script>`.
        if (!OperatingSystem.IsWindows())
        {
            try
            {
                File.SetUnixFileMode(
                    scriptPath,
                    UnixFileMode.UserRead | UnixFileMode.UserWrite | UnixFileMode.UserExecute
                    | UnixFileMode.GroupRead | UnixFileMode.GroupExecute
                    | UnixFileMode.OtherRead | UnixFileMode.OtherExecute);
            }
            catch
            {
                // ignore
            }
        }
    }

    private const string RunnerScript =
        """
        #!/usr/bin/env bash
        # Generated by Testing Agent — reads tests/e2e/cases.json and hits DEPLOYED_URL.
        set -euo pipefail
        BASE_URL="${DEPLOYED_URL:?DEPLOYED_URL is required}"
        BASE_URL="${BASE_URL%/}"
        HERE="$(cd "$(dirname "$0")" && pwd)"
        CASES="$HERE/cases.json"
        OUT="${TA_RESULTS_PATH:-/tmp/ta-results.json}"
        python3 - "$BASE_URL" "$CASES" "$OUT" <<'PY'
        import json, sys, urllib.request
        base, cases_path, out_path = sys.argv[1:4]
        cases = json.load(open(cases_path))["cases"]
        results = []
        all_ok = True
        for c in cases:
            path = c.get("path") or c.get("Path")
            url = base + path
            status = 0
            body = ""
            try:
                with urllib.request.urlopen(url, timeout=30) as r:
                    status = r.status
                    body = r.read().decode("utf-8", errors="replace")
            except Exception as ex:
                body = str(ex)
            expect = int(c.get("expectStatus") or c.get("ExpectStatus") or 200)
            needle = c.get("expectBodyContains") or c.get("ExpectBodyContains") or ""
            ok = status == expect and (needle == "" or needle in body)
            all_ok = all_ok and ok
            results.append({
                "name": c.get("name") or c.get("Name"),
                "path": path,
                "statusCode": status,
                "ok": ok,
                "bodySnippet": body[:240]
            })
        json.dump({"status": "green" if all_ok else "red", "results": results}, open(out_path, "w"), indent=2)
        print("TA smoke:", "green" if all_ok else "red", "->", out_path)
        if not all_ok:
            sys.exit(1)
        PY
        """;

    private static string? ExtractJson(string? text)
    {
        if (string.IsNullOrWhiteSpace(text))
        {
            return null;
        }

        var start = text.LastIndexOf('{');
        var end = text.LastIndexOf('}');
        if (start < 0 || end <= start)
        {
            return null;
        }

        var slice = text[start..(end + 1)];
        try
        {
            using var _ = JsonDocument.Parse(slice);
            return slice;
        }
        catch (JsonException)
        {
            return null;
        }
    }
}

public sealed record SmokeCase(
    string Name,
    string Method,
    string Path,
    int ExpectStatus,
    string? ExpectBodyContains);
